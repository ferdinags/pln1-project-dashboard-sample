const STORAGE_KEY_UIP2B = "pmo_uip2b_subitems_v2";

function loadMasterProjects() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY_MASTER);
    if (stored) return JSON.parse(stored);
  } catch (e) {
    console.warn("Could not load master projects from localStorage", e);
  }
  return INITIAL_MASTER_PROJECTS;
}

function saveMasterProjects(data) {
  try {
    localStorage.setItem(STORAGE_KEY_MASTER, JSON.stringify(data));
  } catch (e) {
    console.error("Failed to save master projects", e);
  }
}

function loadBagSubItems() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY_BAG);
    if (stored) return JSON.parse(stored);
  } catch (e) {
    console.warn("Could not load BAg items", e);
  }
  return INITIAL_BAG_SUB_ITEMS;
}

